// THROWAWAY experiment: stable references via OCCT's own modification history
// (BRepBuilderAPI_MakeShape::Generated / Modified / IsDeleted), driven directly through the raw bindings.
// A "ref" is a logical name -> the list of current sub-shapes that name denotes. Each op updates the refs
// from its own delta, so a name survives edits (follows splits) or is reported as destroyed (never silently
// re-pointed at a different edge, which is what index and pure-geometry queries can do).
import { getOC, cast, iterTopo, drawRectangle, measureVolume } from "replicad";

function drain(list) {
  const out = [];
  while (list.Size() > 0) {
    out.push(list.First());
    list.RemoveFirst();
  }
  return out;
}

export class Refs {
  constructor() {
    this.map = new Map(); // name -> raw shapes
    this.log = []; // human-readable events
  }
  set(name, shapes) {
    this.map.set(name, shapes);
  }
  get(name) {
    return this.map.get(name) ?? [];
  }
  /** Advance every ref across one finished boolean/fillet builder. */
  follow(builder, opName) {
    for (const [name, shapes] of this.map) {
      const next = [];
      let deleted = 0;
      let modified = 0;
      for (const s of shapes) {
        if (builder.IsDeleted(s)) {
          deleted++;
          continue;
        }
        const mod = drain(builder.Modified(s));
        if (mod.length) {
          modified++;
          next.push(...mod);
        } else next.push(s);
      }
      if (!next.length) this.log.push(`${opName}: ${name} destroyed`);
      else if (deleted || modified || next.length !== shapes.length)
        this.log.push(`${opName}: ${name} ${modified ? `modified into ${next.length} piece(s)` : ""}${deleted ? ` (${deleted} destroyed)` : ""}`.trim());
      this.map.set(name, next);
    }
  }
  status(name) {
    return this.get(name).length ? "alive" : "destroyed";
  }
}

/** Extrude a w x d rectangle by h; refs corner_0..3 point at the vertical edge generated by each profile corner. */
export function plateWithCornerRefs(w, d, h) {
  const oc = getOC();
  const face = drawRectangle(w, d).sketchOnPlane("XY").face();
  const vertices = [...iterTopo(face.wrapped, "vertex")];
  const prism = new oc.BRepPrimAPI_MakePrism(face.wrapped, new oc.gp_Vec(0, 0, h), false, true);
  if (!prism.IsDone()) throw new Error("prism failed");
  const refs = new Refs();
  vertices.forEach((v, i) => {
    const edges = drain(prism.Generated(v));
    refs.set(`corner_${i}`, edges);
  });
  return { solid: prism.Shape(), refs };
}

/** Cut a box [min,max] out of the solid, advancing refs. */
export function cutBox(solid, refs, min, max, opName) {
  const oc = getOC();
  const tool = new oc.BRepPrimAPI_MakeBox(new oc.gp_Pnt(...min), new oc.gp_Pnt(...max));
  const cut = new oc.BRepAlgoAPI_Cut(solid, tool.Shape());
  if (cut.HasErrors()) throw new Error("cut failed");
  refs.follow(cut, opName);
  return cut.Shape();
}

/** Fillet every live edge behind the named refs. Returns the filleted solid. */
export function filletRefs(solid, refs, names, radius) {
  const oc = getOC();
  const b = new oc.BRepFilletAPI_MakeFillet(solid, oc.ChFi3d_FilletShape.ChFi3d_Rational);
  let n = 0;
  for (const name of names)
    for (const e of refs.get(name)) {
      b.Add(radius, cast(e).wrapped);
      n++;
    }
  if (!n) throw new Error("no live edges to fillet");
  return b.Shape();
}

export function volumeOf(rawShape) {
  return measureVolume(cast(rawShape));
}

export function heightOf(rawEdge) {
  const b = cast(rawEdge).boundingBox.bounds;
  return b[1][2] - b[0][2];
}
